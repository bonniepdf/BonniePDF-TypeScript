/**
 * Font weight values following the CSS/OpenType weight scale.
 * Standard PDF fonts support Normal (400) and Bold (700).
 * Custom TTF fonts may support additional weights.
 */
export enum FontWeight {
  Thin = 100,
  ExtraLight = 200,
  Light = 300,
  Normal = 400,
  Medium = 500,
  SemiBold = 600,
  Bold = 700,
  ExtraBold = 800,
  Black = 900,
}
