#!/usr/bin/env node
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const coreRoot = resolve(__dirname, '..');
const outputDir = resolve(coreRoot, '..', 'generated-pdfs', 'pdf-validation', 'pdfa4');
const distEntry = resolve(coreRoot, 'dist', 'index.node.js');

if (!existsSync(distEntry)) {
  console.error(`Missing built entry point: ${distEntry}`);
  console.error(
    'Run `pnpm --dir core run build` before this script, or use `pnpm --dir core run test:pdf-validation`.'
  );
  process.exit(1);
}

const { Color, Document, FontManager, Image, Line, StandardFonts, TextBlock, asPdfA4, settings } =
  await import(distEntry);

// Declare a licence tier for this script. Producing validation samples is not
// production use, so `evaluation` is the honest declaration.
settings.license = 'evaluation';

function uint32be(value) {
  return [(value >>> 24) & 0xff, (value >>> 16) & 0xff, (value >>> 8) & 0xff, value & 0xff];
}

function adler32(bytes) {
  const mod = 65521;
  let a = 1;
  let b = 0;
  for (const byte of bytes) {
    a = (a + byte) % mod;
    b = (b + a) % mod;
  }
  return ((b << 16) | a) >>> 0;
}

function pngChunk(type, data = []) {
  const typeBytes = [...Buffer.from(type, 'ascii')];
  // BonniePDF's PNG loader skips CRC validation, but emit the field so the
  // chunk structure is well-formed. The validation harness is for PDF output,
  // not PNG encoder correctness.
  const crcPlaceholder = [0, 0, 0, 0];
  return [...uint32be(data.length), ...typeBytes, ...data, ...crcPlaceholder];
}

function onePixelRgbPng() {
  // 1x1 RGB PNG, no alpha channel. The IDAT stream uses an uncompressed zlib
  // block because BonniePDF's lightweight PNG loader intentionally supports
  // stored deflate blocks without a bundled zlib dependency.
  const scanline = [0, 255, 0, 0]; // filter byte + red RGB pixel
  const len = scanline.length;
  const nlen = ~len & 0xffff;
  const zlib = [
    0x78,
    0x01,
    0x01,
    len & 0xff,
    (len >>> 8) & 0xff,
    nlen & 0xff,
    (nlen >>> 8) & 0xff,
    ...scanline,
    ...uint32be(adler32(scanline)),
  ];
  const ihdr = [...uint32be(1), ...uint32be(1), 8, 2, 0, 0, 0];
  return Uint8Array.from([
    0x89,
    0x50,
    0x4e,
    0x47,
    0x0d,
    0x0a,
    0x1a,
    0x0a,
    ...pngChunk('IHDR', ihdr),
    ...pngChunk('IDAT', zlib),
    ...pngChunk('IEND'),
  ]);
}

function addParagraph(doc, text, fontName = StandardFonts.Helvetica) {
  const block = new TextBlock(text);
  block.fontName = fontName;
  block.fontSize = 12;
  doc.add(block);
  return block;
}

function generatePdf(factory) {
  const doc = new Document();
  try {
    factory(doc);
    return doc.generateBytes();
  } finally {
    doc.dispose();
  }
}

function assertContains(text, needle, sampleName) {
  if (!text.includes(needle)) throw new Error(`${sampleName}: expected output to contain ${needle}`);
}

function assertNotContains(text, needle, sampleName) {
  if (text.includes(needle)) throw new Error(`${sampleName}: expected output not to contain ${needle}`);
}

function assertPdfA4Claim(bytes, sampleName) {
  const text = Buffer.from(bytes).toString('latin1');
  if (!text.startsWith('%PDF-2.0')) throw new Error(`${sampleName}: expected %PDF-2.0 header`);
  assertContains(text, '<pdfaid:part>4</pdfaid:part>', sampleName);
  assertContains(text, '<pdfaid:rev>2020</pdfaid:rev>', sampleName);
  assertNotContains(text, 'pdfaid:conformance', sampleName);
  assertContains(text, '/OutputIntents', sampleName);
}

function assertPdfA4Suppressed(bytes, sampleName) {
  const text = Buffer.from(bytes).toString('latin1');
  if (!text.startsWith('%PDF-2.0')) throw new Error(`${sampleName}: expected %PDF-2.0 header`);
  assertNotContains(text, 'pdfaid:part', sampleName);
  assertNotContains(text, '/OutputIntents', sampleName);
}

function createSamples() {
  const samples = [];

  samples.push({
    name: 'pdfa4-text',
    positive: true,
    bytes: generatePdf(doc => {
      asPdfA4(doc.settings);
      doc.metadata.title = 'BonniePDF PDF/A-4 text validation sample';
      doc.metadata.author = 'BonniePDF validation harness';
      doc.metadata.producer = 'BonniePDF';
      addParagraph(doc, 'PDF/A-4 baseline text sample generated by BonniePDF.', StandardFonts.Helvetica);
      addParagraph(
        doc,
        'This sample avoids transparency, soft masks, encryption, and attachments.',
        StandardFonts.TimesRoman
      );
    }),
  });

  samples.push({
    name: 'pdfa4-image',
    positive: true,
    bytes: generatePdf(doc => {
      asPdfA4(doc.settings);
      doc.metadata.title = 'BonniePDF PDF/A-4 image validation sample';
      addParagraph(doc, 'PDF/A-4 baseline image sample with an RGB PNG.', StandardFonts.Helvetica);
      const image = new Image();
      image.imageData = onePixelRgbPng();
      image.width = 36;
      image.height = 36;
      image.altText = 'One-pixel RGB sample image';
      doc.add(image);
    }),
  });

  samples.push({
    name: 'pdfa4-transparency-mitigated',
    positive: true,
    bytes: generatePdf(doc => {
      asPdfA4(doc.settings);
      doc.metadata.title = 'BonniePDF PDF/A-4 transparency mitigation sample';
      const line = new Line();
      line.length = 240;
      line.thickness = 18;
      line.color = Color.blue.withAlpha(0.35);
      doc.add(line);
    }),
  });

  samples.push({
    name: 'negative-standard-font-suppressed',
    positive: false,
    bytes: generatePdf(doc => {
      // Simulate an environment where the standard-14 substitution fonts are unavailable.
      FontManager.clear();
      asPdfA4(doc.settings);
      addParagraph(doc, 'This file requested PDF/A-4 but uses an unembedded standard font.', StandardFonts.Helvetica);
    }),
  });

  return samples;
}

function commandExists(command) {
  return spawnSync('sh', ['-lc', `command -v ${command}`], { encoding: 'utf8' }).status === 0;
}

function runCommand(command, args, label) {
  const result = spawnSync(command, args, { encoding: 'utf8' });
  return {
    label,
    command: [command, ...args].join(' '),
    status: result.status ?? 1,
    stdout: result.stdout ?? '',
    stderr: result.stderr ?? '',
  };
}

function validateWithAvailableTools(samples) {
  const checks = [];
  const haveQpdf = commandExists('qpdf');
  const haveMutool = commandExists('mutool');
  const haveVeraPdf = commandExists('verapdf');

  for (const sample of samples) {
    const file = join(outputDir, `${sample.name}.pdf`);
    if (haveQpdf) checks.push(runCommand('qpdf', ['--check', file], `qpdf ${sample.name}`));
    else checks.push({ label: `qpdf ${sample.name}`, skipped: true, reason: 'qpdf not found on PATH' });

    if (haveMutool) checks.push(runCommand('mutool', ['info', file], `mutool ${sample.name}`));
    else checks.push({ label: `mutool ${sample.name}`, skipped: true, reason: 'mutool not found on PATH' });

    if (sample.positive) {
      if (haveVeraPdf) checks.push(runCommand('verapdf', ['--format', 'text', file], `veraPDF ${sample.name}`));
      else checks.push({ label: `veraPDF ${sample.name}`, skipped: true, reason: 'verapdf not found on PATH' });
    }
  }

  return checks;
}

function printCheck(check) {
  if (check.skipped) {
    console.warn(`⚠ ${check.label}: skipped (${check.reason})`);
    return;
  }

  if (check.status === 0) {
    console.log(`✓ ${check.label}`);
    return;
  }

  console.error(`✗ ${check.label}: ${check.command}`);
  if (check.stdout.trim()) console.error(check.stdout.trim());
  if (check.stderr.trim()) console.error(check.stderr.trim());
}

rmSync(outputDir, { recursive: true, force: true });
mkdirSync(outputDir, { recursive: true });

const samples = createSamples();
for (const sample of samples) {
  if (sample.positive) assertPdfA4Claim(sample.bytes, sample.name);
  else assertPdfA4Suppressed(sample.bytes, sample.name);
  const file = join(outputDir, `${sample.name}.pdf`);
  writeFileSync(file, sample.bytes);
  console.log(`wrote ${file}`);
}

const checks = validateWithAvailableTools(samples);
for (const check of checks) printCheck(check);

const failures = checks.filter(check => !check.skipped && check.status !== 0);
const report = {
  outputDir,
  generatedAt: new Date().toISOString(),
  samples: samples.map(sample => ({ name: sample.name, positive: sample.positive, bytes: sample.bytes.length })),
  checks,
};
writeFileSync(join(outputDir, 'validation-report.json'), JSON.stringify(report, null, 2));

if (failures.length > 0) {
  console.error(
    `${failures.length} installed validator check(s) failed. See ${join(outputDir, 'validation-report.json')}.`
  );
  process.exit(1);
}

console.log(`PDF/A-4 validation samples generated in ${outputDir}`);
