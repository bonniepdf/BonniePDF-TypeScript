/**
 * Text alignment options for paragraph and text block elements.
 */
export enum TextAlignment {
  /** Text is aligned to the left edge */
  Left = 0,

  /** Text is centered horizontally */
  Center = 1,

  /** Text is aligned to the right edge */
  Right = 2,

  /** Text is centered vertically (for vertical layout contexts) */
  Middle = 3,

  /** Text is justified to fill the full width (spreads words evenly) */
  Justify = 4,
}
